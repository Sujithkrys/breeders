from pathlib import Path
# Builds the dot-matrix world map for the Apple Pay India film from world-atlas (Natural Earth 1:110m, TopoJSON):
# land dots on a hex grid (equirectangular), each tagged with its country, plus the order countries "light up".
# Writes src/apple-pay/map.ts. Run: python scripts/applepay-map.py
import json
from PIL import Image, ImageDraw

SRC = str(Path(__file__).resolve().parent.parent / "assets/geo/countries-110m.json")
OUT = str(Path(__file__).resolve().parent.parent / "src/apple-pay/map.ts")
W = 1760                       # map width in px (1920 frame, 80px margins)
LAT0, LAT1 = 78, -56           # crop: skip Antarctica and the far Arctic
H = round(W * (LAT0 - LAT1) / 360)
STEP = 11                      # dot spacing (px)

topo = json.load(open(SRC))
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]
arcs = []
for arc in topo["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)

def ring(idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts

def proj(lon, lat):
    return (lon + 180) / 360 * W, (LAT0 - lat) / (LAT0 - LAT1) * H

# Rasterise every country into an id mask (country index + 1).
mask = Image.new("I", (W, H), 0)
draw = ImageDraw.Draw(mask)
geoms = topo["objects"]["countries"]["geometries"]
ids = []
for k, g in enumerate(geoms):
    ids.append(g.get("id"))
    polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]] if g["type"] == "Polygon" else []
    for poly in polys:
        for j, r in enumerate(poly):
            pts = [proj(lon, lat) for lon, lat in ring(r)]
            if len(pts) > 2:
                draw.polygon(pts, fill=(k + 1) if j == 0 else 0)
mpx = mask.load()

dots, owner = [], []
row = 0
y = STEP / 2
while y < H:
    x = STEP / 2 + (STEP / 2 if row % 2 else 0)
    while x < W:
        v = mpx[int(x), int(y)]
        if v:
            dots.append((round(x, 1), round(y, 1)))
            owner.append(ids[v - 1])
        x += STEP
    y += STEP * 0.866
    row += 1

# Countries in roughly the order Apple Pay reached them (the film shows no names or years per country, only the
# rolling year counter, so this is pacing, not a claim). ISO 3166 numeric ids; tiny places get a radius instead.
ORDER = [
    (2014, ["840"]),
    (2015, ["826", "124", "036"]),
    (2016, ["156", "756", "250", "392", "554", "724", "372", ("SG", 1.35, 103.8), ("HK", 22.3, 114.2)]),
    (2017, ["380", "158", "784", "208", "752", "246"]),
    (2018, ["076", "616", "578", "276", "040"]),
    (2019, ["528", "056", "484"]),
    (2020, ["682"]),
    (2021, [("IL", 31.4, 35.0), "710", ("QA", 25.3, 51.2), "170"]),
    (2022, ["152", "604"]),
    (2023, ["410"]),
    (2024, ["704", "818"]),
    (2025, ["458", "360"]),
]
countries = []
for year, cs in ORDER:
    for c in cs:
        if isinstance(c, tuple):
            name, lat, lon = c
            px, py = proj(lon, lat)
            idx = [i for i, (x, y) in enumerate(dots) if (x - px) ** 2 + (y - py) ** 2 < (STEP * 1.6) ** 2]
            if not idx:  # no land dot that small: add one
                dots.append((round(px, 1), round(py, 1))); owner.append(name); idx = [len(dots) - 1]
            countries.append({"id": name, "year": year, "dots": idx})
        else:
            idx = [i for i, o in enumerate(owner) if o == c]
            if idx:
                countries.append({"id": c, "year": year, "dots": idx})
            else:
                print("no dots for", c)
india = [i for i, o in enumerate(owner) if o == "356"]
ix = sum(dots[i][0] for i in india) / len(india)
iy = sum(dots[i][1] for i in india) / len(india)
with open(OUT, "w", encoding="utf8") as f:
    f.write("// Generated by scripts/applepay-map.py from world-atlas countries-110m (Natural Earth): land dots on a hex grid,\n")
    f.write(f"// equirectangular {W}×{H}px (lat {LAT0}° to {LAT1}°). COUNTRIES lists dot indices in the order they light up.\n")
    f.write(f"export const MAP = {{ w: {W}, h: {H}, step: {STEP} }};\n")
    f.write("export const DOTS: [number, number][] = " + json.dumps(dots, separators=(",", ":")) + ";\n")
    f.write("export const COUNTRIES: { id: string; year: number; dots: number[] }[] = " + json.dumps(countries, separators=(",", ":")) + ";\n")
    f.write("export const INDIA: number[] = " + json.dumps(india, separators=(",", ":")) + ";\n")
    f.write(f"export const INDIA_AT = {{ x: {ix:.1f}, y: {iy:.1f} }};\n")
print(f"{len(dots)} dots, {len(countries)} countries, India {len(india)} dots at ({ix:.0f},{iy:.0f}), map {W}x{H}")
